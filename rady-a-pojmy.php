        <li>Kupující složí kupní cenu na vázaný účet.</li>
        <li>Banka sleduje, zda došlo ke splnění sjednaných podmínek - například zápisem do katastru.</li>
        <li>Jakmile jsou podmínky splněny, banka peníze uvolní prodávajícímu.</li>
