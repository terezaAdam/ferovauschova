        <li><strong>Transparentnost</strong> – obě strany mají jasný přehled o stavu uložených prostředků.</li>
        <li><strong>Právní jistota</strong> – uložení na úschovní účet je často podmínkou smluvních ujednání, která zajišťují spravedlivé a bezpečné dokončení transakce.</li>
      </ul>

