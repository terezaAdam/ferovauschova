      <h2>Vázaný účet</h2>
      <p>Vázaný účet je bankovní produkt, který se využívá při důležitých transakcích - například při koupi nemovitosti i jako nástroj ochrany financí. Funguje podobně jako advokátní úschova, ale místo advokáta správu a výplatu prostředků zajišťuje banka.</p>
      <p>Peníze jsou na účtu „vázány“ až do splnění předem sjednaných podmínek. Jakmile jsou tyto podmínky naplněny (například zápisem do katastru), banka peníze uvolní druhé straně. Do té doby s nimi nemůže nakládat ani kupující, ani prodávající.</p>
