      <h2>Úschovní účet</h2>
      <p>Úschovní účet je speciální bankovní účet, který slouží k bezpečnému uložení finančních prostředků během určité transakce nebo právního jednání. Na úschovní účet jsou peníze uloženy po dohodnutou dobu a jsou oddělené od běžných provozních financí majitele či jiné třetí strany.</p>
      <p>Tento účet se často využívá například při nemovitostních obchodech, kdy kupující složí kupní cenu na úschovní účet, který je veden nezávislou třetí stranou, dokud nejsou splněny všechny podmínky pro převod nemovitosti.</p>
      <p><strong>Výhody úschovního účtu:</strong></p>
      <ul>
